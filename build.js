// Builds questions.js from the content files and checks every question.
// Usage: node build.js            (content files can sit next to this file, or in a src/ folder)
//        node build.js --strict   (also fails if any "why this option is wrong" data is missing)
const fs = require("fs"), path = require("path"), vm = require("vm");
const STRICT = process.argv.includes("--strict");
const dir = __dirname;
const src = fs.existsSync(path.join(dir, "src", "00-prelude.js")) ? path.join(dir, "src") : dir;
const order = ["00-prelude.js","polity.js","economy.js","environment.js","geography.js","modern.js","ancient.js","culture.js","science.js"];
const pyq = fs.readdirSync(src).filter(f => /^pyq-\d{4}\.js$/.test(f)).sort();
const tailFiles = ["coffee.js"].filter(f => fs.existsSync(path.join(src, f)));
const files = order.filter(f => fs.existsSync(path.join(src, f))).concat(pyq, tailFiles);
const UPDATED = "26 Oct 2026";
const body = files.map(f => "/* ---- " + f + " ---- */\n" + fs.readFileSync(path.join(src, f), "utf8")).join("\n");
const out = "/* Generated by build.js from the content files. Edit those, not this file. */\n(function(){\n" + body +
  "\nwindow.QUESTIONS = Q;\nwindow.FACTS = typeof F !== \"undefined\" ? F : [];\nwindow.CONTENT = {updated: " + JSON.stringify(UPDATED) + "};\n})();\n";

const ctx = {window:{}, encodeURIComponent};
vm.runInNewContext(out, ctx);
const Q = ctx.window.QUESTIONS, FACTS = ctx.window.FACTS;
const SUBJ = ["polity","economy","environment","geography","modern","ancient","culture","science"];
const RN = ["I","II","III","IV","V","VI","VII","VIII"];
const NUMW = {none:0, one:1, two:2, three:3, four:4, five:5, six:6};
const IDRX = /^[A-Za-z0-9][A-Za-z0-9._~-]{0,60}$/;
function parseOpt(t){
  const s = String(t).trim(); let m;
  if(/^none(\b|$)/i.test(s)) return {count:0, set:[]};
  if((m = /^only (one|two|three|four|five|six)\b/i.exec(s))) return {count:NUMW[m[1].toLowerCase()]};
  if((m = /^all (?:the )?(two|three|four|five|six)\b/i.exec(s))) return {count:NUMW[m[1].toLowerCase()]};
  if(/^neither\b/i.test(s)) return {set:[]};
  const r = s.match(/\b(VIII|VII|VI|IV|V|III|II|I)\b/g);
  if(r) return {set:r.map(x => RN.indexOf(x)).sort((a,b) => a-b)};
  const a = s.match(/\b[1-9]\b/g);
  if(a) return {set:a.map(x => +x - 1).sort((a,b) => a-b)};
  return null;
}
function negQ(q){ return q.neg === true || (q.neg !== false && /\b(not correct|incorrect|not correctly)\b/i.test((q.stem || "") + " " + (q.tail || ""))); }
// Which options are consistent with the per-statement truth values?
function consistentOptions(q, truth){
  const opts = q.opts, n = truth.length, k = truth.filter(Boolean).length, neg = negQ(q);
  const want = truth.map((t, i) => (neg ? !t : t) ? i : -1).filter(i => i > -1);
  return opts.map((o, i) => {
    const p = parseOpt(o); if(!p) return {i, ok:false, parsed:false};
    if(p.count !== undefined) return {i, ok:p.count === (neg ? n - k : k), parsed:true};
    return {i, ok:JSON.stringify(p.set) === JSON.stringify(want), parsed:true};
  });
}
const errs = [], warns = [], ids = new Set();
const isStr = (x, min) => typeof x === "string" && x.trim().length >= (min || 1);
Q.forEach(q => {
  const e = m => errs.push(q.id + ": " + m), w = m => warns.push(q.id + ": " + m);
  if(!IDRX.test(q.id)) e("bad id"); if(ids.has(q.id)) e("duplicate id"); ids.add(q.id);
  if(!["easy","exam"].includes(q.mode)) e("mode");
  if(!SUBJ.includes(q.subj)) e("subj");
  if(!["mcq","statements","match","assertion"].includes(q.type)) e("type");
  if(q.mode === "easy" && q.type !== "mcq") e("easy must be mcq");
  const opts = q.opts || (q.type === "assertion" ? [1,2,3,4] : null);
  if(!opts || opts.length !== 4) e("needs 4 options");
  if(!Number.isInteger(q.ans) || q.ans < 0 || q.ans > 3) e("ans");
  if(q.opts && new Set(q.opts).size !== q.opts.length) e("duplicate options");
  if(!q.stem || !q.why || q.why.length < 60) e("stem/why");
  if(!q.take || q.take.length > 140) e("takeaway missing or too long (" + (q.take||"").length + ")");
  if(!q.topic) e("topic");
  if(!q.links || !q.links.length || !q.links.every(l => l.t && /^https:\/\//.test(l.u))) e("links");
  if(q.type === "statements" && !(q.items && q.items.length >= 2 && q.tail)) e("statements incomplete");
  if(q.type === "match" && !(q.pairs && q.pairs.length >= 3 && q.heads && q.heads.length === 2 && q.tail)) e("match incomplete");
  if(q.type === "assertion" && !(q.s1 && q.s2)) e("assertion incomplete");
  if(q.mode === "exam" && q.num !== "arabic" && q.opts && q.opts.some(o => /\b[1-9]\b/.test(o))) e("arabic numerals in roman-numbered options");
  if(q.mode === "exam" && q.num !== "arabic" && /\b(statements?|pairs?) [1-9]\b/i.test(q.why)) e("explanation cites arabic statement numbers");
  if(q.num === "arabic" && q.opts && q.opts.some(o => /\b(II|III|IV)\b/.test(o))) e("roman numerals in arabic-numbered options");
  // past-paper provenance
  if(q.pyq !== undefined){
    if(!(q.pyq && Number.isInteger(q.pyq.y) && q.pyq.y >= 2013 && q.pyq.y <= 2026 && Number.isInteger(q.pyq.q) && q.pyq.q >= 1 && q.pyq.q <= 100)) e("pyq {y,q} malformed");
    else if(q.tag !== "PYQ " + q.pyq.y) e("tag must be 'PYQ " + q.pyq.y + "'");
  } else if(/PYQ/.test(q.tag || "")) e("PYQ tag without pyq provenance");
  // "why this option is wrong" data
  if(q.type === "mcq"){
    if(!q.wn) w("no wn");
    else if(!(Array.isArray(q.wn) && q.wn.length === 4 && q.wn.every((x, i) => i === q.ans ? x === null : isStr(x, 15)))) e("wn must be 4 entries, null at the answer, a reason elsewhere");
  }
  if(q.type === "statements" || q.type === "match"){
    const pair = q.type === "match", v = pair ? q.pv : q.sv, r = pair ? q.pr : q.sr, n = pair ? (q.pairs||[]).length : (q.items||[]).length;
    if(!v) w("no " + (pair ? "pv/pr" : "sv/sr"));
    else {
      if(!(Array.isArray(v) && v.length === n && v.every(x => x === 0 || x === 1))) e((pair ? "pv" : "sv") + " must be 0/1 per item");
      else if(!(Array.isArray(r) && r.length === n && r.every(x => isStr(x, 15)))) e((pair ? "pr" : "sr") + " must give a reason per item");
      else {
        const c = consistentOptions(q, v.map(Boolean));
        if(c.some(x => !x.parsed)) e("could not read option codes: " + c.filter(x => !x.parsed).map(x => q.opts[x.i]).join(" | "));
        else {
          const okIdx = c.filter(x => x.ok).map(x => x.i);
          if(okIdx.length !== 1 || okIdx[0] !== q.ans) e("truth values " + JSON.stringify(v) + " point to option(s) " + JSON.stringify(okIdx) + " but the key is " + q.ans);
        }
      }
    }
  }
  if(q.type === "assertion"){
    if(!q.av) w("no av/ar");
    else if(!(Array.isArray(q.av) && q.av.length === 3 && q.av.every(x => x === 0 || x === 1) && Array.isArray(q.ar) && q.ar.length === 3 && q.ar.every(x => isStr(x, 15)))) e("av must be [I,II,explains] 0/1 and ar three reasons");
    else {
      const [a, b, x] = q.av, implied = a && b ? (x ? 0 : 1) : a && !b ? 2 : !a && b ? 3 : -1;
      if(implied !== q.ans) e("av " + JSON.stringify(q.av) + " implies option " + implied + " but the key is " + q.ans);
    }
  }
  if(q.cx !== undefined && typeof q.cx !== "string") e("cx must be a string");
  if(q.cf !== undefined && !(q.cf === false || Array.isArray(q.cf))) e("cf must be false or a list of indexes");
});
const fids = new Set();
FACTS.forEach(f => {
  const e = m => errs.push((f.id || "?") + ": " + m);
  if(!IDRX.test(f.id || "")) e("bad fact id"); if(fids.has(f.id) || ids.has(f.id)) e("duplicate fact id"); fids.add(f.id);
  if(!SUBJ.includes(f.subj)) e("fact subj");
  if(!isStr(f.text, 15) || f.text.length > 200) e("fact text missing or over 200 characters");
  if(typeof f.truth !== "boolean") e("fact truth must be true/false");
  if(!isStr(f.why, 20) || f.why.length > 260) e("fact why missing or over 260 characters");
  if(f.link && !(f.link.t && /^https:\/\//.test(f.link.u))) e("fact link");
});
const count = {}, pos = {easy:[0,0,0,0], exam:[0,0,0,0]}, types = {};
Q.forEach(q => { const k = q.subj + "/" + q.mode; count[k] = (count[k]||0) + 1; pos[q.mode][q.ans]++; types[q.type] = (types[q.type]||0) + 1; });
const pyqs = Q.filter(q => q.pyq), byYear = {};
pyqs.forEach(q => { byYear[q.pyq.y] = (byYear[q.pyq.y]||0) + 1; });
const derived = Q.reduce((s, q) => s + (q.sv ? q.sv.length : 0) + (q.pv ? q.pv.length : 0) + (q.av ? 2 : 0), 0);
console.log("Files:", files.join(", "));
console.log("Questions:", Q.length, "| easy", Q.filter(q => q.mode === "easy").length, "| exam", Q.filter(q => q.mode === "exam").length, "| PYQ", pyqs.length, JSON.stringify(byYear));
console.log("By subject/mode:", JSON.stringify(count));
console.log("By type:", JSON.stringify(types));
console.log("Answer positions (a,b,c,d):", JSON.stringify(pos));
console.log("Coffee Break: " + FACTS.length + " standalone facts (" + FACTS.filter(f => f.truth).length + " true / " + FACTS.filter(f => !f.truth).length + " false) + " + derived + " statements from Exam questions");
if(warns.length) console.log("Missing 'why wrong' data: " + warns.length + (warns.length <= 12 ? "\n- " + warns.join("\n- ") : " (run with --strict to list)"));
if(STRICT && warns.length) warns.forEach(w => errs.push(w));
if(errs.length){ console.log("ERRORS:\n- " + errs.join("\n- ")); process.exit(1); }
fs.writeFileSync(path.join(dir, "questions.js"), out);
console.log("questions.js written (" + out.length + " bytes)");
